"""Phrases to listen for, and their variants: Ukrainian and Russian case forms, transliterations and
common mishearings, all generated by rule. Multi-word phrases are declined together (Тараса Маслова,
Тарасові Маслову).

`compile_phrase()` turns a phrase into what the matcher needs: each variant reduced to one
normalized Latin form (detect.clean), with its kind (form | translit | mishearing | claude).
"""
from __future__ import annotations

import itertools
import re

from .detect import clean, phonetic

DEFAULT_PHRASES = ["тарас", "тарас маслов", "маслов"]
SLOTS = ("nom", "gen", "dat", "acc", "ins", "loc", "voc", "pl")

# Russian <-> Ukrainian/Latin letters for spelling a Latin-only phrase in Cyrillic.
_LAT2CYR = [("shch", "щ"), ("zh", "ж"), ("kh", "х"), ("ts", "ц"), ("ch", "ч"), ("sh", "ш"), ("yu", "ю"),
            ("ya", "я"), ("a", "а"), ("b", "б"), ("v", "в"), ("w", "в"), ("g", "г"), ("h", "г"), ("d", "д"),
            ("e", "е"), ("z", "з"), ("i", "і"), ("y", "и"), ("k", "к"), ("l", "л"), ("m", "м"), ("n", "н"),
            ("o", "о"), ("p", "п"), ("r", "р"), ("s", "с"), ("t", "т"), ("u", "у"), ("f", "ф"), ("c", "к")]


def is_cyrillic(w: str) -> bool:
    return any("Ѐ" <= ch <= "ӿ" for ch in w)


def to_cyrillic(w: str) -> str:
    w, out = w.lower(), ""
    while w:
        for lat, cyr in _LAT2CYR:
            if w.startswith(lat):
                out, w = out + cyr, w[len(lat):]
                break
        else:
            out, w = out + w[0], w[1:]
    return out


def declension(word: str) -> dict[str, list[str]]:
    """Case forms of one word by slot, Ukrainian and Russian together. Lowercase Cyrillic."""
    w = word.lower()
    m = re.match(r"^(.+?)(ов|ев|єв|ёв|ин|ін|ын)$", w)
    if m and len(w) >= 4:   # -ов / -ев / -ин surnames, masculine, feminine and plural
        s, suf = m.group(1), m.group(2)
        st = s + suf
        return {
            "nom": [st, st + "а"],
            "gen": [st + "а", st + "ої", st + "ой", st + "их", st + "ых"],
            "dat": [st + "у", st + "ові", st + "ій", st + "ой", st + "им", st + "ым"],
            "acc": [st + "а", st + "у", st + "их", st + "ых"],
            "ins": [st + "им", st + "ым", st + "ою", st + "ой", st + "ими", st + "ыми"],
            "loc": [st + "і", st + "е", st + "ові", st + "ій", st + "ой", st + "их", st + "ых"],
            "voc": [st + "е", st, st + "о"],
            "pl": [st + "и", st + "ы", st + "их", st + "ых"],
        }
    if re.search(r"[аяa]$", w):   # first declension: Олена, Маша
        s = w[:-1]
        return {"nom": [w], "gen": [s + "и", s + "ы", s + "і"], "dat": [s + "і", s + "е"], "acc": [s + "у", s + "ю"],
                "ins": [s + "ою", s + "ой", s + "ей"], "loc": [s + "і", s + "е"], "voc": [s + "о", s + "е"],
                "pl": [s + "и", s + "ы"]}
    if re.search(r"[бвгґджзклмнпрстфхцчшщ]$", w):   # consonant-final masculine: Тарас, Иван
        return {"nom": [w], "gen": [w + "а"], "dat": [w + "у", w + "ові"], "acc": [w + "а"],
                "ins": [w + "ом"], "loc": [w + "і", w + "ові", w + "е"], "voc": [w + "е", w],
                "pl": [w + "и", w + "ы", w + "ів", w + "ов"],
                "dim": [w + "ик", w + "ика", w + "ику", w + "иком", w + "ко", w + "ка", w + "ко"]}
    return {"nom": [w]}


# Alternative Latin spellings of a normalized form (beyond detect.translit's one).
_LATIN_ALTS = [(r"ov$", ["ow", "off", "of", "ev"]), (r"ova$", ["owa", "offa"]), (r"kh", ["h", "ch"]),
               (r"^ye", ["e", "je"]), (r"yi", ["i", "ji"]), (r"zh", ["j", "zh", "sz"]), (r"ts", ["tz", "c"]),
               (r"shch", ["sch", "shh"]), (r"ch", ["tch", "cz"]),
               (r"sh", ["sch", "sz"])]


def translits(norm: str) -> set[str]:
    out = {norm}
    for pat, reps in _LATIN_ALTS:
        for v in list(out):
            if re.search(pat, v):
                for r in reps:
                    out.add(re.sub(pat, r, v))
        if len(out) > 24:
            break
    return out


def mishearings(norm: str) -> set[str]:
    """What speech recognition commonly writes instead: an unstressed vowel changed, a doubled or
    voiced/unvoiced consonant, a final v heard as f."""
    out = set()
    vowels = [i for i, ch in enumerate(norm) if ch in "aoe"]
    for i in vowels:
        for alt in "aoe":
            if alt != norm[i]:
                out.add(norm[:i] + alt + norm[i + 1:])
    for i in range(1, len(norm)):
        if norm[i] in "rslnt" and norm[i - 1] in "aeiou":
            out.add(norm[:i] + norm[i] + norm[i:])
    out |= {re.sub(r"v$", "f", norm), re.sub(r"s$", "z", norm), re.sub(r"s", "ss", norm, count=1)}
    out.discard(norm)
    return {o for o in out if len(o) >= 4}


def variants(text: str, extra: list[str] | None = None) -> dict:
    """{"text", "variants": [display strings], "compiled": [...]} for one phrase."""
    words = [w for w in re.split(r"\s+", text.strip().lower()) if w]
    cyr = [w if is_cyrillic(w) else to_cyrillic(w) for w in words]
    tables = [declension(w) for w in cyr]
    slots = set().union(*[set(t) for t in tables]) if tables else set()
    forms: list[str] = []
    seen = set()
    for slot in [s for s in SLOTS if s in slots] + sorted(slots - set(SLOTS)):
        per_word = [t.get(slot) or t.get("nom") for t in tables]
        for combo in itertools.product(*per_word):
            f = " ".join(combo)
            if f not in seen:
                seen.add(f)
                forms.append(f)
    if " ".join(words) not in seen:
        forms.insert(0, " ".join(words))
        seen.add(" ".join(words))
    compiled: dict[str, dict] = {}

    def add(norm: str, kind: str, shown: str, sound: float):
        if norm and (norm not in compiled or compiled[norm]["sound"] < sound):
            compiled[norm] = {"norm": norm, "kind": kind, "shown": shown, "sound": sound,
                              "words": len(norm.split())}

    base = " ".join(clean(w) for w in cyr)
    for f in forms:
        n = " ".join(clean(w) for w in f.split())
        add(n, "form", f, 0.95 if n == base else 0.9)
    for f in list(compiled.values()):
        if f["kind"] != "form":
            continue
        parts = f["norm"].split()
        alts = [sorted(translits(p)) for p in parts]
        for combo in itertools.islice(itertools.product(*alts), 40):
            n = " ".join(combo)
            add(n, "translit", n.title(), 0.85)
    for f in [v for v in compiled.values() if v["kind"] == "form"][:12]:
        parts = f["norm"].split()
        for i, p in enumerate(parts):
            for mis in sorted(mishearings(p)):
                n = " ".join(parts[:i] + [mis] + parts[i + 1:])
                add(n, "mishearing", n, 0.55)
    for e in extra or []:
        n = " ".join(clean(w) for w in e.split())
        add(n, "claude", e, 0.6)
    shown = []
    for v in compiled.values():
        if v["kind"] in ("form", "translit", "claude") and v["shown"] not in shown:
            shown.append(v["shown"])
    for v in list(compiled.values()):
        if v["kind"] == "form" and v["norm"].title() not in shown:
            shown.append(v["norm"].title())
    return {"text": text.strip(), "variants": shown,
            "mishearings": sorted(v["norm"] for v in compiled.values() if v["kind"] == "mishearing"),
            "compiled": list(compiled.values()),
            "phonetic": sorted({phonetic(w) for w in base.split()})}


def claude_expand(text: str, ask) -> list[str]:
    """Ask Claude once for further spellings and mishearings of a phrase. `ask(prompt) -> str`."""
    prompt = (f"List up to 25 ways speech recognition (Whisper) might write the name/phrase \"{text}\" when it is "
              "spoken in Ukrainian, Russian, English, German, French, Polish or Spanish speech: grammatical forms, "
              "transliterations, and plausible mishearings. One per line, no numbering, no explanations.")
    out = []
    for line in (ask(prompt) or "").splitlines():
        line = line.strip(" -*•\t\"'")
        if line and len(line) <= 40 and not line.lower().startswith(("here", "note")):
            out.append(line)
    return out[:25]
