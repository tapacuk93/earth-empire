import { useEffect, useState } from 'preact/hooks';
import { getAdminSettings, putAdminSettings, type AdminSettings, acceptPhraseSuggestion, adminToken, checkAdmin, getPhrases, getPhraseSuggestions, rejectPhraseSuggestion, rescan, savePhrases, setAdminToken, useOwner, type Phrase, type PhraseSuggestion } from '../live';
import { getHighlights } from '../api';
import { setMeta } from '../util';

export function OwnerToken({ onChange, inputRef }: { onChange: (ok: boolean) => void; inputRef?: preact.Ref<HTMLInputElement> }) {
  const [token, setToken] = useState(adminToken());
  const [msg, setMsg] = useState('');
  const has = !!adminToken();
  const save = async (e: Event) => {
    e.preventDefault();
    setMsg('Checking…');
    try {
      if (await checkAdmin(token.trim())) { setAdminToken(token.trim()); setMsg('Signed in as the owner on this device.'); onChange(true); }
      else setMsg('That token was not accepted.');
    } catch (err) { setMsg(`Could not check the token: ${(err as Error).message}`); }
  };
  return (
    <form class="token-form" onSubmit={save}>
      <label for="admin-token" class="sr-only">Owner token</label>
      <div class="row">
        <input id="admin-token" ref={inputRef} type="password" autocomplete="off" value={token} onInput={(e) => setToken((e.target as HTMLInputElement).value)} placeholder="Only the owner has it" />
        <button class="btn small" type="submit" disabled={!token.trim()}>Check and keep</button>
        {has && <button class="btn small ghost" type="button" onClick={() => { setAdminToken(''); setToken(''); setMsg('Signed out on this device.'); onChange(false); }}>Sign out</button>}
      </div>
      <p class="muted small" role="status">{msg || 'Kept only in this browser. It turns on the owner’s screens: Detected, Settings and Status.'}</p>
    </form>
  );
}

function Phrases({ owner }: { owner: boolean }) {
  const [list, setList] = useState<Phrase[]>();
  const [draft, setDraft] = useState<string[]>([]);
  const [add, setAdd] = useState('');
  const [msg, setMsg] = useState('');
  const [busy, setBusy] = useState(false);
  const [sugs, setSugs] = useState<PhraseSuggestion[]>([]);
  const loadSugs = (texts: string[]) => getPhraseSuggestions(texts, () => getHighlights().then((hs) => hs.map((h) => h.title))).then(setSugs, () => setSugs([]));
  const load = () => getPhrases().then((p) => { setList(p); setDraft(p.map((x) => x.text)); loadSugs(p.map((x) => x.text)); }, (e) => setMsg(`Could not load the phrases: ${e.message}`));
  useEffect(() => { load(); }, []);
  const dirty = !!list && JSON.stringify(draft) !== JSON.stringify(list.map((x) => x.text));
  const variants = (t: string) => { const p = list?.find((x) => x.text === t); return p ? [...new Set([...(p.variants || []), ...(p.claude_variants || []), ...(p.mishearings || [])])] : []; };

  const save = async () => {
    setBusy(true); setMsg('Saving…');
    try {
      const clean = [...new Set(draft.map((d) => d.trim()).filter(Boolean))];
      const p = await savePhrases(clean);
      setList(p); setDraft(p.map((x) => x.text)); loadSugs(p.map((x) => x.text)); setMsg('Saved. Variants are generated by the monitor.');
    } catch (e) { setMsg(`Could not save: ${(e as Error).message}`); }
    setBusy(false);
  };
  const accept = async (t: string) => {
    setBusy(true); setMsg(`Adding “${t}”…`);
    try {
      const p = await acceptPhraseSuggestion(t, (list || []).map((x) => x.text));
      setList(p); setDraft(p.map((x) => x.text)); setSugs(sugs.filter((x) => x.text !== t)); setMsg(`Added “${t}”.`);
    } catch (e) { setMsg(`Could not add it: ${(e as Error).message}`); }
    setBusy(false);
  };
  const reject = async (t: string) => {
    try { await rejectPhraseSuggestion(t); setSugs(sugs.filter((x) => x.text !== t)); setMsg(`Will not suggest “${t}” again.`); }
    catch (e) { setMsg(`Could not reject it: ${(e as Error).message}`); }
  };
  const doRescan = async () => {
    setBusy(true); setMsg('Asking the monitor to re-check stored transcripts…');
    try { await rescan(); setMsg('Rescan started. Progress shows under Activity.'); } catch (e) { setMsg(`Could not start a rescan: ${(e as Error).message}`); }
    setBusy(false);
  };

  return (
    <section class="panel" aria-labelledby="phrases-h">
      <h2 id="phrases-h">Phrases the monitor listens for</h2>
      {!list ? <p class="muted">{msg || 'Loading…'}</p> : (
        <>
          <ul class="phrases" role="list">
            {draft.map((t, i) => (
              <li key={i} class="phrase">
                {owner ? (
                  <input aria-label={`Phrase ${i + 1}`} value={t} onInput={(e) => { const d = draft.slice(); d[i] = (e.target as HTMLInputElement).value; setDraft(d); }} />
                ) : <span class="phrase-text">{t}</span>}
                {owner && <button class="icon-btn" aria-label={`Remove “${t}”`} onClick={() => setDraft(draft.filter((_, j) => j !== i))}>×</button>}
                {variants(t).length > 0 && (
                  <ul class="variants" role="list" aria-label={`Variants of “${t}”`}>{variants(t).map((v) => <li key={v}>{v}</li>)}</ul>
                )}
              </li>
            ))}
          </ul>
          {owner ? (
            <>
              <form class="row" onSubmit={(e) => { e.preventDefault(); if (add.trim()) { setDraft([...draft, add.trim()]); setAdd(''); } }}>
                <label class="sr-only" for="new-phrase">New phrase</label>
                <input id="new-phrase" value={add} placeholder="Add a phrase" onInput={(e) => setAdd((e.target as HTMLInputElement).value)} />
                <button class="btn small" type="submit" disabled={!add.trim()}>Add</button>
              </form>
              <div class="row">
                <button class="btn" onClick={save} disabled={busy || !dirty}>Save</button>
                <button class="btn ghost" onClick={doRescan} disabled={busy}>Rescan stored transcripts</button>
              </div>
            </>
          ) : <p class="muted small">Read-only. The owner edits these after entering the owner token above.</p>}
          {owner && sugs.length > 0 && (
            <section aria-labelledby="sugs-h" class="sugs">
              <h3 id="sugs-h">Suggested phrases</h3>
              <ul class="phrases" role="list">
                {sugs.map((sg) => (
                  <li key={sg.text} class="phrase">
                    <span class="phrase-text">{sg.text}{sg.reason && <span class="muted small"> · {sg.reason}</span>}</span>
                    <button class="btn small" disabled={busy} onClick={() => accept(sg.text)} aria-label={`Accept “${sg.text}”`}>Accept</button>
                    <button class="btn small ghost" onClick={() => reject(sg.text)} aria-label={`Reject “${sg.text}”`}>Reject</button>
                  </li>
                ))}
              </ul>
            </section>
          )}
          <p class="muted small" role="status">{msg}</p>
        </>
      )}
    </section>
  );
}

const PLACEMENT_LABEL: Record<string, string> = { post: 'Own post', dedicated: 'Dedicated highlight', shared: 'Common highlight', repost: 'Repost', story: 'Story', hit_top: 'Detected, upper', hit_bottom: 'Detected, lower' };
const fmtWhen = (s?: string) => (s ? new Date(s).toLocaleString('en', { dateStyle: 'medium', timeStyle: 'short' }) : '');

/** How tile sizes are computed: the importance rubric (versioned), w, age decay and placement weights. */
function Importance() {
  const [st, setSt] = useState<AdminSettings>();
  const [draft, setDraft] = useState<AdminSettings>();
  const [reason, setReason] = useState('');
  const [msg, setMsg] = useState('');
  const [busy, setBusy] = useState(false);
  const load = () => getAdminSettings().then((x) => { setSt(x); setDraft(JSON.parse(JSON.stringify(x))); }, (e) => setMsg(`Could not load: ${e.message}`));
  useEffect(() => { load(); }, []);
  if (!st || !draft) return <section class="panel" aria-labelledby="imp-h"><h2 id="imp-h">Importance</h2><p class="muted">{msg || 'Loading…'}</p></section>;
  const num = (v: string) => (v === '' ? undefined : Number(v));
  const rubricChanged = draft.rubric.text.trim() !== st.rubric.text.trim();
  const sizeChanged = JSON.stringify(draft.size) !== JSON.stringify(st.size);
  const placeChanged = JSON.stringify(draft.placement) !== JSON.stringify(st.placement);
  const save = async () => {
    setBusy(true); setMsg('Saving…');
    try {
      const next = await putAdminSettings({
        ...(sizeChanged ? { size: draft.size } : {}), ...(placeChanged ? { placement: draft.placement } : {}),
        ...(rubricChanged ? { rubric: { text: draft.rubric.text.trim(), reason: reason.trim() || undefined } } : {}),
      });
      setSt(next); setDraft(JSON.parse(JSON.stringify(next))); setReason('');
      setMsg(rubricChanged ? `Saved. The rubric is now version ${next.rubric.version}; items are re-scored in the background.` : 'Saved.');
    } catch (e) { setMsg(`Could not save: ${(e as Error).message}`); }
    setBusy(false);
  };
  const history = (st.rubric.history || []).slice().sort((a, b) => b.version - a.version);
  return (
    <section class="panel importance" aria-labelledby="imp-h">
      <h2 id="imp-h">Importance</h2>
      <p class="formula"><code>{st.formula || 'size = placement × age_factor × (1 − w + w × importance)'}</code></p>
      <div class="imp-grid">
        <label>w (weight of importance)<input type="number" step="0.01" min="0" max="1" value={draft.size.importance_w ?? ''} onInput={(e) => setDraft({ ...draft, size: { ...draft.size, importance_w: num((e.target as HTMLInputElement).value) } })} /></label>
        <label>Age half-life (days)<input type="number" step="1" min="1" value={draft.size.half_life_days ?? ''} onInput={(e) => setDraft({ ...draft, size: { ...draft.size, half_life_days: num((e.target as HTMLInputElement).value) } })} /></label>
        <label>Age floor<input type="number" step="0.01" min="0" max="1" value={draft.size.age_floor ?? ''} onInput={(e) => setDraft({ ...draft, size: { ...draft.size, age_floor: num((e.target as HTMLInputElement).value) } })} /></label>
      </div>
      <h3>Placement weights</h3>
      <div class="imp-grid">
        {Object.entries(draft.placement).map(([k, v]) => (
          <label key={k}>{PLACEMENT_LABEL[k] || k}<input type="number" step="0.005" min="0" max="1" value={v} onInput={(e) => setDraft({ ...draft, placement: { ...draft.placement, [k]: Number((e.target as HTMLInputElement).value) } })} /></label>
        ))}
      </div>
      <h3>Importance rubric <span class="muted small">version {st.rubric.version}{st.rubric.by ? `, by ${st.rubric.by}` : ''}</span></h3>
      <label class="sr-only" for="rubric">Importance rubric</label>
      <textarea id="rubric" rows={6} value={draft.rubric.text} onInput={(e) => setDraft({ ...draft, rubric: { ...draft.rubric, text: (e.target as HTMLTextAreaElement).value } })} />
      {rubricChanged && <input aria-label="Reason for the change" placeholder="Why this change (kept in the history)" value={reason} onInput={(e) => setReason((e.target as HTMLInputElement).value)} />}
      <div class="row">
        <button class="btn" onClick={save} disabled={busy || !(rubricChanged || sizeChanged || placeChanged)}>Save</button>
        {st.rubric_review !== undefined && <span class="muted small">Claude reviews the rubric daily{st.rubric_review ? '' : ' (off)'}; refinements apply as new versions.</span>}
      </div>
      <p class="muted small" role="status">{msg}</p>
      <details class="history">
        <summary>Rubric history ({history.length})</summary>
        <ol class="plain">
          {history.map((h) => (
            <li key={h.version} class={h.applied === false ? 'not-applied' : ''}>
              <p><b>v{h.version}</b> · {h.by || '?'} · {fmtWhen(h.created_at)}{h.applied === false && ' · proposed, not applied'}</p>
              {h.reason && <p class="muted small">{h.reason}</p>}
              <blockquote>{h.text}</blockquote>
            </li>
          ))}
        </ol>
      </details>
    </section>
  );
}

export function SettingsPage() {
  const owner = useOwner();
  useEffect(() => { setMeta('Settings', undefined, undefined, true); }, []);
  return (
    <>
      <header class="page-head"><h1>{owner ? 'Settings' : 'Owner sign-in'}</h1>
        {!owner && <p class="lead">Earth Empire is public. The owner signs in here with the owner token to see Detected, Status and Settings.</p>}
      </header>
      <section class="panel" aria-labelledby="token-h">
        <h2 id="token-h">Owner token</h2>
        <OwnerToken onChange={() => undefined} />
      </section>
      {owner && <Phrases owner />}
      {owner && <Importance />}
    </>
  );
}

/** Wraps the owner's pages: a visitor gets the sign-in form instead. */
export function OwnerOnly({ children }: { children: preact.ComponentChildren }) {
  const owner = useOwner();
  if (owner === undefined) return <p class="muted page-head">Checking…</p>;
  if (!owner) return <SettingsPage />;
  return <>{children}</>;
}
