import { useEffect, useState } from 'preact/hooks';
import { adminToken, checkAdmin, getPhrases, getStatus, rescan, savePhrases, setAdminToken, type Component, type Phrase, type State, type Status } from '../live';
import { fmtDateTime, setMeta } from '../util';

const STATE_LABEL: Record<State, string> = { ok: 'Working', degraded: 'Degraded', down: 'Down', off: 'Off' };
const rel = (s?: string | null) => {
  if (!s) return 'never';
  const d = (Date.now() - Date.parse(s)) / 1000;
  if (isNaN(d)) return s;
  if (d < 60) return `${Math.max(0, Math.round(d))} s ago`;
  if (d < 3600) return `${Math.round(d / 60)} min ago`;
  if (d < 86400) return `${Math.round(d / 3600)} h ago`;
  return fmtDateTime(s);
};
const pct = (p?: number | null) => (typeof p === 'number' ? Math.round(p > 1 ? p : p * 100) : null);

function Pill({ state }: { state: State }) {
  return <span class={`state s-${state}`}><span class="dot" aria-hidden="true" />{STATE_LABEL[state] || state}</span>;
}

function Details({ d }: { d?: Record<string, unknown> }) {
  const entries = Object.entries(d || {});
  if (!entries.length) return null;
  return (
    <dl class="kv">
      {entries.map(([k, v]) => (
        <div key={k}><dt>{k.replace(/_/g, ' ')}</dt>
          <dd>{v && typeof v === 'object'
            ? Object.entries(v as Record<string, unknown>).map(([a, b]) => `${a.replace(/_/g, ' ')}: ${typeof b === 'object' ? JSON.stringify(b) : String(b)}`).join(' · ')
            : String(v)}</dd></div>
      ))}
    </dl>
  );
}

function ComponentCard({ c }: { c: Component }) {
  return (
    <li class={`comp s-${c.state}`}>
      <div class="comp-head"><h3>{c.name || c.id}</h3><Pill state={c.state} /></div>
      <p class="muted small">Last success {rel(c.last_success)}</p>
      {c.last_error?.message && <p class="comp-err"><span class="sr-only">Last error: </span>{c.last_error.message} <span class="muted small">({rel(c.last_error.at)})</span></p>}
      <Details d={c.details} />
    </li>
  );
}

function OwnerToken({ onChange }: { onChange: (ok: boolean) => void }) {
  const [token, setToken] = useState(adminToken());
  const [msg, setMsg] = useState('');
  const has = !!adminToken();
  const save = async (e: Event) => {
    e.preventDefault();
    setMsg('Checking…');
    try {
      if (await checkAdmin(token.trim())) { setAdminToken(token.trim()); setMsg('Signed in as the owner on this device.'); onChange(true); }
      else setMsg('That token was not accepted.');
    } catch (err) { setMsg(`Could not check the token: ${(err as Error).message}`); }
  };
  return (
    <form class="token-form" onSubmit={save}>
      <label for="admin-token">Owner token</label>
      <div class="row">
        <input id="admin-token" type="password" autocomplete="off" value={token} onInput={(e) => setToken((e.target as HTMLInputElement).value)} placeholder="Only the owner has it" />
        <button class="btn small" type="submit" disabled={!token.trim()}>Check and keep</button>
        {has && <button class="btn small ghost" type="button" onClick={() => { setAdminToken(''); setToken(''); setMsg('Signed out on this device.'); onChange(false); }}>Sign out</button>}
      </div>
      <p class="muted small" role="status">{msg || 'Kept only in this browser. It turns on the owner’s buttons here and in Monitor.'}</p>
    </form>
  );
}

function Phrases({ owner }: { owner: boolean }) {
  const [list, setList] = useState<Phrase[]>();
  const [draft, setDraft] = useState<string[]>([]);
  const [add, setAdd] = useState('');
  const [msg, setMsg] = useState('');
  const [busy, setBusy] = useState(false);
  const load = () => getPhrases().then((p) => { setList(p); setDraft(p.map((x) => x.text)); }, (e) => setMsg(`Could not load the phrases: ${e.message}`));
  useEffect(() => { load(); }, []);
  const dirty = !!list && JSON.stringify(draft) !== JSON.stringify(list.map((x) => x.text));
  const variants = (t: string) => list?.find((p) => p.text === t)?.variants || [];

  const save = async () => {
    setBusy(true); setMsg('Saving…');
    try {
      const clean = [...new Set(draft.map((d) => d.trim()).filter(Boolean))];
      const p = await savePhrases(clean);
      setList(p); setDraft(p.map((x) => x.text)); setMsg('Saved. Variants are generated by the monitor.');
    } catch (e) { setMsg(`Could not save: ${(e as Error).message}`); }
    setBusy(false);
  };
  const doRescan = async () => {
    setBusy(true); setMsg('Asking the monitor to re-check stored transcripts…');
    try { await rescan(); setMsg('Rescan started. Progress shows under Activity.'); } catch (e) { setMsg(`Could not start a rescan: ${(e as Error).message}`); }
    setBusy(false);
  };

  return (
    <section class="panel" aria-labelledby="phrases-h">
      <h2 id="phrases-h">Phrases the monitor listens for</h2>
      {!list ? <p class="muted">{msg || 'Loading…'}</p> : (
        <>
          <ul class="phrases" role="list">
            {draft.map((t, i) => (
              <li key={i} class="phrase">
                {owner ? (
                  <input aria-label={`Phrase ${i + 1}`} value={t} onInput={(e) => { const d = draft.slice(); d[i] = (e.target as HTMLInputElement).value; setDraft(d); }} />
                ) : <span class="phrase-text">{t}</span>}
                {owner && <button class="icon-btn" aria-label={`Remove “${t}”`} onClick={() => setDraft(draft.filter((_, j) => j !== i))}>×</button>}
                {variants(t).length > 0 && (
                  <ul class="variants" role="list" aria-label={`Variants of “${t}”`}>{variants(t).map((v) => <li key={v}>{v}</li>)}</ul>
                )}
              </li>
            ))}
          </ul>
          {owner ? (
            <>
              <form class="row" onSubmit={(e) => { e.preventDefault(); if (add.trim()) { setDraft([...draft, add.trim()]); setAdd(''); } }}>
                <label class="sr-only" for="new-phrase">New phrase</label>
                <input id="new-phrase" value={add} placeholder="Add a phrase" onInput={(e) => setAdd((e.target as HTMLInputElement).value)} />
                <button class="btn small" type="submit" disabled={!add.trim()}>Add</button>
              </form>
              <div class="row">
                <button class="btn" onClick={save} disabled={busy || !dirty}>Save</button>
                <button class="btn ghost" onClick={doRescan} disabled={busy}>Rescan stored transcripts</button>
              </div>
            </>
          ) : <p class="muted small">Read-only. The owner edits these after entering the owner token above.</p>}
          <p class="muted small" role="status">{msg}</p>
        </>
      )}
    </section>
  );
}

export function StatusPage() {
  const [st, setSt] = useState<Status>();
  const [err, setErr] = useState<string>();
  const [owner, setOwner] = useState(!!adminToken());
  useEffect(() => { setMeta('Status', 'Live activity and health of the archive’s parts.'); }, []);
  useEffect(() => {
    let live = true, timer = 0;
    const tick = () => {
      if (!document.hidden) getStatus().then((s) => { if (live) { setSt(s); setErr(undefined); } }, (e) => live && setErr(e.message));
      timer = window.setTimeout(tick, 10000);
    };
    tick();
    const vis = () => { if (!document.hidden) { clearTimeout(timer); tick(); } };
    document.addEventListener('visibilitychange', vis);
    return () => { live = false; clearTimeout(timer); document.removeEventListener('visibilitychange', vis); };
  }, []);

  const jobs = st?.activity?.jobs || [];
  const events = st?.activity?.events || [];
  return (
    <>
      <header class="page-head">
        <h1>Status</h1>
        {st ? <p class="lead">Overall: <Pill state={st.overall} /> <span class="muted small">updated {rel(st.generated_at)}, refreshes every 10 s</span></p>
          : <p class="muted">{err ? `Could not load the status: ${err}` : 'Loading…'}</p>}
        {st && err && <p class="error small" role="alert">Last refresh failed: {err}</p>}
      </header>
      {st && (
        <>
          <section aria-labelledby="comp-h">
            <h2 id="comp-h" class="sr-only">Components</h2>
            <ul class="comps" role="list">{st.components.map((c) => <ComponentCard key={c.id} c={c} />)}</ul>
          </section>
          <section class="panel" aria-labelledby="act-h">
            <h2 id="act-h">Activity</h2>
            <h3>Working on now</h3>
            {jobs.length ? (
              <ul class="jobs" role="list">
                {jobs.map((j, i) => {
                  const p = pct(j.progress);
                  return (
                    <li key={i}>
                      <span class="job-what"><b>{j.component}</b> · {j.item ? <a href={`/item/${encodeURIComponent(j.item)}`}>{j.what}</a> : j.what}</span>
                      {p !== null && <progress max={100} value={p} aria-label={`${j.what}: ${p}%`} />}
                      <span class="muted small">{p !== null ? `${p}% · ` : ''}{typeof j.elapsed_s === 'number' ? `${Math.round(j.elapsed_s)} s` : rel(j.started_at)}</span>
                    </li>
                  );
                })}
              </ul>
            ) : <p class="muted">Nothing running right now.</p>}
            <h3>Latest events</h3>
            <ol class="events">
              {events.map((e, i) => (
                <li key={i} class={e.ok === false ? 'bad' : ''}>
                  <time dateTime={e.at} title={fmtDateTime(e.at)}>{rel(e.at)}</time>
                  <span class="ev-comp">{e.component}</span>
                  <span>{e.ok === false && <span class="sr-only">Failed: </span>}{e.item ? <a href={`/item/${encodeURIComponent(e.item)}`}>{e.text}</a> : e.text}</span>
                </li>
              ))}
            </ol>
          </section>
        </>
      )}
      <section class="panel" aria-labelledby="settings-h">
        <h2 id="settings-h">Settings</h2>
        <OwnerToken onChange={setOwner} />
      </section>
      <Phrases owner={owner} />
    </>
  );
}
